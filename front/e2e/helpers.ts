import { test as base, expect, type BrowserContext, type Page } from '@playwright/test';

export { expect };

/** Collect the console errors and warnings, and the uncaught errors, of a browser context. */
export function watchConsole(context: BrowserContext, into: string[] = []): string[] {
  context.on('console', (msg) => {
    if (msg.type() === 'error' || msg.type() === 'warning') {
      into.push(`${msg.type()}: ${msg.text()} (${msg.location().url})`);
    }
  });
  context.on('weberror', (e) => into.push(`uncaught: ${e.error().message}`));
  return into;
}

/**
 * Subject, "Browser Compatibility": no error or warning in Chrome's console.
 * Only checked on Chromium: Firefox and WebKit log warnings of their own.
 */
export function expectCleanConsole(problems: string[], browserName: string, allowed: RegExp[] = []): void {
  if (browserName !== 'chromium') return;
  expect(
    problems.filter((p) => !allowed.some((re) => re.test(p))),
    'the browser console must stay clean',
  ).toEqual([]);
}

type ConsoleFixtures = {
  /** Accept a console message the test provokes on purpose, e.g. Chrome's log of a 401. */
  allowConsole: (pattern: RegExp) => void;
};

/** Every test fails if its page logs an unexpected console error or warning. */
export const test = base.extend<ConsoleFixtures>({
  allowConsole: [
    async ({ context, browserName }, use) => {
      const allowed: RegExp[] = [];
      const problems = watchConsole(context);
      await use((pattern) => {
        allowed.push(pattern);
      });
      expectCleanConsole(problems, browserName, allowed);
    },
    { auto: true },
  ],
});

