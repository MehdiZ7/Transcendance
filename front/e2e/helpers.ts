/** Navigate to a path and wait for the app shell (banner) to be rendered. */
export async function goto(page: Page, path: string): Promise<void> {
  await page.goto(path);
  await expect(page.getByRole('banner')).toBeVisible();
}

/** A unique-ish suffix usable for created test entities. */
export function uniqueSuffix(): string {
  return `${Date.now()}`;
}

/** Build a listing URL from its public_id. */
export function listingPath(publicId: string): string {
  return `/listings/${publicId}`;
}
